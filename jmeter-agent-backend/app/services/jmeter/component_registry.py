def get_component_meta(testclass: str) -> Dict[str, Any]:
    """获取组件元数据"""
    return COMPONENT_REGISTRY.get(testclass, {
        "label": testclass,
        "icon": "📦",
        "category": "other",
        "allowed_parents": [],
        "allowed_children": [],
        "properties": {},
        "defaults": {},
    })


def get_all_components() -> List[Dict[str, Any]]:
    """获取所有支持的组件列表（含完整元数据）"""
    result = []
    for testclass, meta in COMPONENT_REGISTRY.items():
        result.append({
            "testclass": testclass,
            "label": meta["label"],
            "icon": meta["icon"],
            "category": meta["category"],
            "allowed_parents": meta.get("allowed_parents", []),
            "allowed_children": meta.get("allowed_children", []),
            "properties": meta.get("properties", {}),
            "defaults": meta.get("defaults", {}),
            "special_editor": meta.get("special_editor"),
        })
    return result


def get_allowed_children(parent_testclass: str) -> List[Dict[str, Any]]:
    """获取某个父组件下允许添加的子组件列表"""
    meta = get_component_meta(parent_testclass)
    allowed = meta.get("allowed_children", [])
    return [c for c in get_all_components() if c["testclass"] in allowed]
